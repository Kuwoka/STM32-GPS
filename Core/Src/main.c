void get_nmea_field(char *nmea_str, int field_num, char *output) {
    int comma_count = 0;
    int i = 0, j = 0;
    while (nmea_str[i] != '\0' && nmea_str[i] != '*') {
        if (nmea_str[i] == ',') {
            comma_count++;
            i++;
            continue;
        }
        if (comma_count == field_num) {
            output[j++] = nmea_str[i];
        }
        if (comma_count > field_num) break;
        i++;
    }
    output[j] = '\0';
}

